package co.edu.ue.finalproject.data.model;

public class ServicioDTO {
    private int tipsId;
    private String tipsDescripcion;
    private String tipsNombreServicio;

    public int getTipsId() {
        return tipsId;
    }

    public void setTipsId(int tipsId) {
        this.tipsId = tipsId;
    }

    public String getTipsDescripcion() {
        return tipsDescripcion;
    }

    public void setTipsDescripcion(String tipsDescripcion) {
        this.tipsDescripcion = tipsDescripcion;
    }

    public String getTipsNombreServicio() {
        return tipsNombreServicio;
    }

    public void setTipsNombreServicio(String tipsNombreServicio) {
        this.tipsNombreServicio = tipsNombreServicio;
    }
}
